import { readdirSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { firstDiff, generators, regenerate } from './map_gen';

/**
 * The maps are generated: tools/maps/gen_*.py write src/content/maps/*.ts, and a map is changed by editing its generator and
 * re-running it. Every generator is run here, in a scratch copy of the tree, and each map it writes must equal the committed
 * file byte for byte; a hand edit to a generated map, or a generator edit never re-run, fails with the map and the first line
 * that differs. Every committed map that says it is generated must come from the generator it names.
 */

const GENERATED_BY = /^\/\/ Generated by tools\/maps\/(gen_[A-Za-z0-9_]+\.py)/m;

describe('the maps are their generators\' (byte for byte)', () => {
  const made = new Map<string, string>(); // map → the generator that wrote it

  it.each(generators())('%s reproduces every map it writes', (script) => {
    const maps = regenerate(script);
    expect(maps.length, `${script} wrote no map`).toBeGreaterThan(0);
    const diffs: string[] = [];
    for (const m of maps) {
      const d = firstDiff(m.generated, m.committed);
      if (d) diffs.push(`${m.map}.ts — ${d}`);
      made.set(m.map, script);
    }
    expect(diffs, `${script}: re-run it (python3 tools/maps/${script}), or move the map's hand edit into it`).toEqual([]);
  });

  it('every committed map that says it is generated is written by the generator it names', () => {
    const wrong: string[] = [];
    for (const f of readdirSync('src/content/maps').filter((x) => x.endsWith('.ts')).sort()) {
      const named = GENERATED_BY.exec(readFileSync(`src/content/maps/${f}`, 'utf8'))?.[1];
      if (!named) continue;
      const map = f.replace(/\.ts$/, '');
      // run alone (-t), the generators above have not filled `made`: ask the named one
      const by = made.get(map) ?? (regenerate(named).some((m) => m.map === map) ? named : undefined);
      if (by !== named) wrong.push(`${f}: says ${named}, ${by ? `written by ${by}` : 'which does not write it'}`);
    }
    expect(wrong).toEqual([]);
  });
});
