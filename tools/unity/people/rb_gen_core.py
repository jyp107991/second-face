"""Core's Rocketbox people (L3): data/rb_bodies.json (rb_bodies.py) written as C# (Core/Npc/RbPeopleData.cs), the usable
people only (no 'out'), with each dye group's own colour (the garment's median, CIELAB -> sRGB) and whether it may keep it.
Usage: python rb_gen_core.py [rb_bodies.json] > unity/Assets/SecondFace/Core/Npc/RbPeopleData.cs"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'data', 'rb_bodies.json')
d = json.load(open(src))


def srgb(lab):
    L, a, b = lab
    fy = (L + 16) / 116; fx = fy + a / 500; fz = fy - b / 200
    W = (0.9505, 1.0, 1.089)
    xyz = [(f ** 3 if f > 0.206893 else (f - 16 / 116) / 7.787) * w for f, w in zip((fx, fy, fz), W)]
    M = [[3.2406, -1.5372, -0.4986], [-0.9689, 1.8758, 0.0415], [0.0557, -0.2040, 1.0570]]
    rgb = [sum(M[i][j] * xyz[j] for j in range(3)) for i in range(3)]
    enc = lambda c: 1.055 * max(c, 0) ** (1 / 2.4) - 0.055 if c > 0.0031308 else 12.92 * max(c, 0)
    v = [min(255, max(0, int(round(enc(c) * 255)))) for c in rgb]
    return (v[0] << 16) | (v[1] << 8) | v[2]


rows = []
for p in d['people']:
    if p.get('out') or not p.get('roles'): continue
    dye = p.get('dye') or [None, None, None]
    own = [srgb(g['lab']) if g else -1 for g in dye]
    kind = [('"%s"' % g['own']) if g and g.get('own') else 'null' for g in dye]
    roles = ', '.join('"%s"' % r for r in p['roles'])
    rows.append('            new RbPerson { Id = "%s", Male = %s, Age = %d, People = %s, Style = "%s", Roles = new[] { %s }, '
                'Own = new[] { %s }, OwnKind = new string[] { %s } },' % (
                    p['id'], 'true' if p['sex'] == 'm' else 'false', int(p.get('age') or 35),
                    ('"%s"' % p['people']) if p.get('people') else 'null', p['style'], roles,
                    ', '.join('0x%06x' % o if o >= 0 else '-1' for o in own), ', '.join(kind)))
print('''// Generated by tools/unity/people/rb_gen_core.py from tools/unity/people/data/rb_bodies.json. Do not edit.
namespace SecondFace.Core.Npc
{
    public static class RbPeopleData
    {
        public static readonly RbPerson[] All =
        {
%s
        };
    }
}''' % '\n'.join(rows))
