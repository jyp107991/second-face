"""Writes Core's data for the sculptor on Rocketbox heads (RocketboxSculptData.cs) from rocketbox_features.json: the
measured features, each calibrated slider's millimetres per unit on each feature (each end), and per head the room each
feature has on each side before it leaves the library's spread (or the published spread where the library holds a
feature fixed). Core's RocketboxSculpt turns these into each slider's limits and holds sliders that share a feature
jointly. Usage: python3 rocketbox_gen_core.py <rocketbox_features.json> <out.cs>"""
import json, sys

def main(src, out):
    d = json.load(open(src))
    sliders = list(d['sliders'])
    feats = list(next(iter(d['sexes'].values()))['features'])
    eff = d['mm_per_unit']; sd = d.get('published_sd', {})
    f = lambda x: f'{x:.2f}'
    L = ['// Generated by tools/unity/people/rocketbox_gen_core.py from rocketbox_features.json; do not edit.',
         'using System.Collections.Generic;', '', 'namespace SecondFace.Core.Npc', '{',
         '    /// <summary>The sculptor on Rocketbox heads, calibrated feature by feature (owner, 2026-10-31; see',
         '    /// docs/PEOPLE_RESEARCH.md section 7): the features measured on the library\'s heads (mm), each calibrated',
         '    /// slider\'s change of each feature per unit at each end (mm), and per head each feature\'s room below and above',
         '    /// its own value before it leaves the library\'s [5, 95] % for its sex.</summary>',
         '    public static class RocketboxSculptData', '    {',
         '        public static readonly string[] Features = { ' + ', '.join(f'"{x}"' for x in feats) + ' };',
         '        public static readonly string[] Sliders = { ' + ', '.join(f'"{x}"' for x in sliders) + ' };', '',
         '        /// <summary>By slider: the change of each feature (in <see cref="Features"/> order) per unit at its low',
         '        /// end and at its high end, mm.</summary>',
         '        public static readonly Dictionary<string, (double[] Low, double[] High)> Effect = new()', '        {']
    for s in sliders:
        lo = [eff[s].get('decr', {}).get(ft, 0.0) for ft in feats]
        hi = [eff[s].get('incr', {}).get(ft, 0.0) for ft in feats]
        L.append(f'            ["{s}"] = (new double[] {{ {", ".join(map(f, lo))} }}, new double[] {{ {", ".join(map(f, hi))} }}),')
    L += ['        };', '',
          '        /// <summary>By head: each feature\'s room (mm) below (negative or zero) and above (positive or zero) the',
          '        /// head\'s own value (999 where the feature could not be measured on the head: no bound).</summary>',
          '        public static readonly Dictionary<string, (double[] Below, double[] Above)> Room = new()', '        {']
    for name, face in sorted(d['faces'].items()):
        dist = d['sexes'][face['sex']]['features']; own = face['features']
        below, above = [], []
        for ft in feats:
            v = own.get(ft)
            if v is None or v != v: below.append(-999.0); above.append(999.0); continue   # not measured: no bound
            lo, hi = dist[ft]['p5'], dist[ft]['p95']
            if ft in sd and hi - lo < 1.0: lo, hi = v - 1.645 * sd[ft], v + 1.645 * sd[ft]
            below.append(min(0.0, lo - v)); above.append(max(0.0, hi - v))
        L.append(f'            ["{name}"] = (new double[] {{ {", ".join(map(f, below))} }}, new double[] {{ {", ".join(map(f, above))} }}),')
    L += ['        };', '    }', '}']
    open(out, 'w').write('\n'.join(L) + '\n')
    print('wrote', out, len(sliders), 'sliders', len(feats), 'features', len(d['faces']), 'heads')

if __name__ == '__main__':
    main(*sys.argv[1:3])
