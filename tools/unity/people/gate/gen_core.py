"""Core's table for the proportions solver (docs/PEOPLE_REALISM.md §4.1-4.2): the bases' measures and their response to
each sculptor shape (response.json, from response.py), the real people's measures per sex and race (ansur_stats.json,
ANSUR II), the bases' face proportions and their response (response2d.json, from response2d.py) and the real faces'
proportions per race, sex and age band (fairface_stats.json, FairFace), written as C# so Core needs no files at run time.
Writes unity/Assets/SecondFace/Core/Npc/ProportionsData.cs.
Usage: python3 gen_core.py"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', '..', 'unity', 'Assets', 'SecondFace', 'Core', 'Npc', 'ProportionsData.cs')


def arr(xs, nd=3):
    return 'new double[] { ' + ', '.join(f'{x:.{nd}f}' for x in xs) + ' }'


def main():
    R = json.load(open(os.path.join(HERE, 'response.json')))
    A = json.load(open(os.path.join(HERE, 'ansur_stats.json')))
    assert R['measures'] == A['measures'][:len(R['measures'])], 'the response and ANSUR measures must line up'
    L = ['// Generated by tools/unity/people/gate/gen_core.py from response.json and ansur_stats.json; do not edit.',
         'using System.Collections.Generic;', '', 'namespace SecondFace.Core.Npc', '{',
         '    /// <summary>The proportions solver\'s data (<see cref="Proportions"/>): the measures in order, each base\'s measures',
         '    /// at neutral and their change per unit of each shape side (mm, at the base\'s own stature), and the real people\'s',
         '    /// measures per ANSUR II group (mean, covariance, 3rd and 97th percentiles of the measures and of their ratios).</summary>',
         '    public static class ProportionsData', '    {',
         '        public static readonly string[] Measures = { ' + ', '.join(f'"{m}"' for m in A['measures']) + ' };',
         '        public static readonly string[] Ratios = { ' + ', '.join(f'"{r}"' for r in A['ratios']) + ' };', '']
    for base in ('f', 'm'):
        b = R[base]
        L.append(f'        public static readonly double[] Neutral_{base} = {arr(b["neutral"])};')
        L.append(f'        public static readonly Dictionary<string, double[]> Response_{base} = new()')
        L.append('        {')
        for tag, v in sorted(b['shapes'].items()):
            if max(abs(x) for x in v) < 0.05: continue   # no measurable effect
            L.append(f'            ["{tag}"] = {arr(v)},')
        L.append('        };')
        L.append('')
    # the faces' landmark proportions (response2d.json, FairFace): the bases' and their response, the real groups'
    R2p = os.path.join(HERE, 'response2d.json')
    F = json.load(open(os.path.join(HERE, 'fairface_stats.json')))
    L.append('        public static readonly string[] Ratios2 = { ' + ', '.join(f'"{r}"' for r in F['ratios']) + ' };')
    if os.path.exists(R2p):
        R2 = json.load(open(R2p))
        assert R2['ratios'] == F['ratios'], 'the 2D response and FairFace ratios must line up'
        for base in ('f', 'm'):
            b = R2[base]
            L.append(f'        public static readonly double[] Neutral2_{base} = {arr(b["neutral"], 5)};')
            L.append(f'        public static readonly Dictionary<string, double[]> Response2_{base} = new()')
            L.append('        {')
            for tag, v in sorted(b['shapes'].items()):
                if max(abs(x) for x in v) < 0.002: continue
                L.append(f'            ["{tag}"] = {arr(v, 5)},')
            L.append('        };')
    else:
        for base in ('f', 'm'):
            L.append(f'        public static readonly double[] Neutral2_{base} = null;')
            L.append(f'        public static readonly Dictionary<string, double[]> Response2_{base} = new();')
    L.append('')
    L.append('        /// <summary>A FairFace group\'s face proportions: the mean of the age band (else of all ages), the covariance of')
    L.append('        /// all its ages (steadier), and the 5th and 95th percentiles the gate holds a face to (the band\'s when it has')
    L.append('        /// 25 faces, else all ages\', as tools/unity/people/gate/gate.py chooses).</summary>')
    L.append('        public sealed class Faces2 { public double[] Mean, Cov, P5, P95; }')
    L.append('        public static readonly Dictionary<string, Faces2> FaceGroups = new()')
    L.append('        {')
    for key, g in F['groups'].items():
        race, sex, band = key.split('/')
        if band != 'all' and g['n'] < 25: continue
        allg = F['groups'][f'{race}/{sex}/all']
        cov = [x for row in allg['cov'] for x in row]
        L.append(f'            ["{key}"] = new Faces2 {{ Mean = {arr(g["mean"], 4)}, Cov = {arr(cov, 7)}, P5 = {arr(g["p5"], 4)}, P95 = {arr(g["p95"], 4)} }},')
    L.append('        };')
    L.append('')
    L.append('        /// <summary>A group\'s real measures; <c>Joint</c>: the whitened distance of the head and neck measures from the')
    L.append('        /// group\'s mean given the stature under which 97.5 % of its real people lie (held out; gate.py\'s 3D check).')
    L.append('        /// <c>Bmi</c>: each measure\'s covariance with the body mass index given the stature, in mm per sd of it.</summary>')
    L.append('        public sealed class Group { public double[] Mean, Cov, P3, P97, RatioP3, RatioP97, Bmi; public double Joint; }')
    L.append('        public static readonly Dictionary<string, Group> Groups = new()')
    L.append('        {')
    for key, g in A['groups'].items():
        m, r = g['measures'], g['ratios']
        cov = [x for row in m['cov'] for x in row]
        L.append(f'            ["{key}"] = new Group')
        L.append('            {')
        L.append(f'                Mean = {arr(m["mean"])},')
        L.append(f'                Cov = {arr(cov)},')
        L.append(f'                P3 = {arr(m["p3"])}, P97 = {arr(m["p97"])},')
        L.append(f'                RatioP3 = {arr(r["p3"], 4)}, RatioP97 = {arr(r["p97"], 4)},')
        L.append(f'                Joint = {g["joint"]["p975"]:.4f}, Bmi = {arr(g["bmi"])},')
        L.append('            },')
    L.append('        };')
    L.append('    }')
    L.append('}')
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(OUT))
    faces_table()


def faces_table():
    """Core's real faces (R3, faces_fit.json): per FairFace race and sex, each real face at rest as the sculptor's slider
    values that give our base its shape, with its age class and its landmark ratios; and the sliders' real range per sex
    (their 2nd-98th percentiles over the real faces, a tenth of the span wider), which replaces the hand-written ranges.
    Writes unity/Assets/SecondFace/Core/Npc/FacesData.cs."""
    import numpy as np
    fp = os.path.join(HERE, 'faces_fit.json')
    if not os.path.exists(fp): return
    fit = json.load(open(fp))
    shapes = {f['i']: f for f in json.load(open(os.path.join(HERE, 'fairface_shapes.json')))['faces']}
    ratios = {i: f['r'] for i, f in shapes.items()}
    F = json.load(open(os.path.join(HERE, 'fairface_stats.json')))['ratios']
    ids = sorted({k for f in fit['faces'] for k in f['sliders']})
    # the sliders the real faces set: those that move a frontal face measurably (the rest, the profile, the ears and the
    # head's depth, keep their ancestry's rules)
    resp = {}
    for sex in ('f', 'm'):
        for tag, v in fit['response'][sex]['shapes'].items():
            resp[tag[:-2]] = max(resp.get(tag[:-2], 0.0), float(np.linalg.norm(v)))
    import sys
    sys.path.insert(0, HERE)
    from faces_fit import PROFILE
    sets = [i for i in ids if resp.get(i, 0.0) >= 0.4 and i not in PROFILE]
    L = ['// Generated by tools/unity/people/gate/gen_core.py from faces_fit.json and fairface_shapes.json; do not edit.',
         'using System.Collections.Generic;', '', 'namespace SecondFace.Core.Npc', '{',
         '    /// <summary>Real faces (R3, docs/PEOPLE_REALISM.md §4.2): FairFace\'s frontal faces at rest, each as the sculptor\'s',
         '    /// slider values that give our base its shape (tools/unity/people/gate/faces_fit.py), with its age class (3: 20-29 ..',
         '    /// 8: 70+) and its landmark ratios (<see cref="ProportionsData.Ratios2"/>); by FairFace race and sex. And each',
         '    /// slider\'s real range per sex.</summary>',
         '    public static class FacesData', '    {',
         '        public static readonly string[] Sliders = { ' + ', '.join(f'"{i}"' for i in ids) + ' };',
         '        /// <summary>The sliders the real faces set (those that move a frontal face measurably).</summary>',
         '        public static readonly string[] Set = { ' + ', '.join(f'"{i}"' for i in sets) + ' };',
         '        /// <summary>A real face: its FairFace index, age class, slider values, landmark ratios and whole shape in its sex\'s',
         '        /// whitened shape space (faces_fit.json).</summary>',
         '        public sealed class Real { public int Id, Age; public float[] V; public double[] R; public float[] Z; }', '']
    from faces_fit import slider_ranges
    from gate import face_model
    for sex in ('f', 'm'):
        V = np.array([[f['sliders'].get(i, 0.0) for i in ids] for f in fit['faces'] if f['sex'] == sex])
        lo, hi = np.percentile(V, 2, 0), np.percentile(V, 98, 0)
        pad = 0.1 * (hi - lo)
        # never past a slider's own reach (Sculpt.Extended)
        reach = slider_ranges(sex == 'm', True)
        bound = np.array([reach[i][2] if i in reach else 1.0 for i in ids])
        L.append(f'        public static readonly float[] Lo_{sex} = {{ ' + ', '.join(f'{x:.3f}f' for x in np.maximum(lo - pad, -bound)) + ' };')
        L.append(f'        public static readonly float[] Hi_{sex} = {{ ' + ', '.join(f'{x:.3f}f' for x in np.minimum(hi + pad, bound)) + ' };')
    # the gate's 2D proportions check (gate.py face_model, without the age rule): the ratios it holds, the spread within a
    # people pooled per sex, and the distance from a people's mean that holds the real faces at its coverage
    keys = [k for k in F if k != 'nose_len']
    real = [f for f in json.load(open(os.path.join(HERE, 'fairface_shapes.json')))['faces'] if f['gap'] < 0.035]
    M = face_model(real, fit['space'], keys)
    L.append('        /// <summary>The 2D gate\'s proportions check (gate.py): the ratios it holds (indices into R), each sex\'s')
    L.append('        /// pooled within-people covariance of them and the distance from a people\'s mean real faces keep to.</summary>')
    L.append('        public static readonly int[] Held = { ' + ', '.join(str(F.index(k)) for k in keys) + ' };')
    for sex in ('f', 'm'):
        C = M[sex]['L'] @ M[sex]['L'].T
        L.append(f'        public static readonly double[] Cov2_{sex} = {{ ' + ', '.join(f'{x:.8f}' for x in C.ravel()) + ' };')
        L.append(f'        public const double Lim2_{sex} = {M[sex]["lim_r"]:.4f};')
        L.append(f'        public static readonly double[] ShapeSd_{sex} = {{ ' + ', '.join(f'{x:.5f}' for x in M[sex]['sZ']) + ' };')
        L.append(f'        public const double LimShape_{sex} = {M[sex]["lim_s"]:.4f};')
    from shapes import symmetric
    def zs(f):
        sp = fit['space'][f['sex']]
        return np.array(sp['comps']) @ (symmetric(shapes[f['i']]['shape']) - np.array(sp['mean'])) / np.array(sp['sd'])
    L.append('        public static readonly Dictionary<string, Real[]> Groups = new()')
    L.append('        {')
    groups = {}
    for f in fit['faces']: groups.setdefault(f"{f['race']}/{f['sex']}", []).append(f)
    for key, fs in sorted(groups.items()):
        L.append(f'            ["{key}"] = new Real[]')
        L.append('            {')
        for f in fs:
            v = ', '.join(f"{f['sliders'].get(i, 0.0):.3f}f" for i in ids)
            r = ', '.join(f'{ratios[f["i"]][k]:.4f}' for k in F)
            z = ', '.join(f'{x:.4f}f' for x in zs(f))
            L.append(f'                new Real {{ Id = {f["i"]}, Age = {f["age"]}, V = new float[] {{ {v} }}, R = new double[] {{ {r} }}, Z = new float[] {{ {z} }} }},')
        L.append('            },')
    L.append('        };')
    L.append('    }')
    L.append('}')
    out = os.path.join(os.path.dirname(OUT), 'FacesData.cs')
    open(out, 'w').write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(out), sum(len(v) for v in groups.values()), 'real faces,', len(ids), 'sliders')


if __name__ == '__main__':
    main()
