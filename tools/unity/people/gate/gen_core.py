"""Core's table for the proportions solver (docs/PEOPLE_REALISM.md §4.1-4.2): the bases' measures and their response to
each sculptor shape (response.json, from response.py), the real people's measures per sex and race (ansur_stats.json,
ANSUR II), the bases' face proportions and their response (response2d.json, from response2d.py) and the real faces'
proportions per race, sex and age band (fairface_stats.json, FairFace), written as C# so Core needs no files at run time.
Writes unity/Assets/SecondFace/Core/Npc/ProportionsData.cs.
Usage: python3 gen_core.py"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', '..', 'unity', 'Assets', 'SecondFace', 'Core', 'Npc', 'ProportionsData.cs')


def arr(xs, nd=3):
    return 'new double[] { ' + ', '.join(f'{x:.{nd}f}' for x in xs) + ' }'


def main():
    R = json.load(open(os.path.join(HERE, 'response.json')))
    A = json.load(open(os.path.join(HERE, 'ansur_stats.json')))
    assert R['measures'] == A['measures'][:len(R['measures'])], 'the response and ANSUR measures must line up'
    L = ['// Generated by tools/unity/people/gate/gen_core.py from response.json and ansur_stats.json; do not edit.',
         'using System.Collections.Generic;', '', 'namespace SecondFace.Core.Npc', '{',
         '    /// <summary>The proportions solver\'s data (<see cref="Proportions"/>): the measures in order, each base\'s measures',
         '    /// at neutral and their change per unit of each shape side (mm, at the base\'s own stature), and the real people\'s',
         '    /// measures per ANSUR II group (mean, covariance, 3rd and 97th percentiles of the measures and of their ratios).</summary>',
         '    public static class ProportionsData', '    {',
         '        public static readonly string[] Measures = { ' + ', '.join(f'"{m}"' for m in A['measures']) + ' };',
         '        public static readonly string[] Ratios = { ' + ', '.join(f'"{r}"' for r in A['ratios']) + ' };', '']
    for base in ('f', 'm'):
        b = R[base]
        L.append(f'        public static readonly double[] Neutral_{base} = {arr(b["neutral"])};')
        L.append(f'        public static readonly Dictionary<string, double[]> Response_{base} = new()')
        L.append('        {')
        for tag, v in sorted(b['shapes'].items()):
            if max(abs(x) for x in v) < 0.05: continue   # no measurable effect
            L.append(f'            ["{tag}"] = {arr(v)},')
        L.append('        };')
        L.append('')
    # the faces' landmark proportions (response2d.json, FairFace): the bases' and their response, the real groups'
    R2p = os.path.join(HERE, 'response2d.json')
    F = json.load(open(os.path.join(HERE, 'fairface_stats.json')))
    L.append('        public static readonly string[] Ratios2 = { ' + ', '.join(f'"{r}"' for r in F['ratios']) + ' };')
    if os.path.exists(R2p):
        R2 = json.load(open(R2p))
        assert R2['ratios'] == F['ratios'], 'the 2D response and FairFace ratios must line up'
        for base in ('f', 'm'):
            b = R2[base]
            L.append(f'        public static readonly double[] Neutral2_{base} = {arr(b["neutral"], 5)};')
            L.append(f'        public static readonly Dictionary<string, double[]> Response2_{base} = new()')
            L.append('        {')
            for tag, v in sorted(b['shapes'].items()):
                if max(abs(x) for x in v) < 0.002: continue
                L.append(f'            ["{tag}"] = {arr(v, 5)},')
            L.append('        };')
    else:
        for base in ('f', 'm'):
            L.append(f'        public static readonly double[] Neutral2_{base} = null;')
            L.append(f'        public static readonly Dictionary<string, double[]> Response2_{base} = new();')
    L.append('')
    L.append('        /// <summary>A FairFace group\'s face proportions: the mean of the age band (else of all ages), the covariance of')
    L.append('        /// all its ages (steadier), and the 5th and 95th percentiles the gate holds a face to (the band\'s when it has')
    L.append('        /// 25 faces, else all ages\', as tools/unity/people/gate/gate.py chooses).</summary>')
    L.append('        public sealed class Faces2 { public double[] Mean, Cov, P5, P95; }')
    L.append('        public static readonly Dictionary<string, Faces2> FaceGroups = new()')
    L.append('        {')
    for key, g in F['groups'].items():
        race, sex, band = key.split('/')
        if band != 'all' and g['n'] < 25: continue
        allg = F['groups'][f'{race}/{sex}/all']
        cov = [x for row in allg['cov'] for x in row]
        L.append(f'            ["{key}"] = new Faces2 {{ Mean = {arr(g["mean"], 4)}, Cov = {arr(cov, 7)}, P5 = {arr(g["p5"], 4)}, P95 = {arr(g["p95"], 4)} }},')
    L.append('        };')
    L.append('')
    L.append('        public sealed class Group { public double[] Mean, Cov, P3, P97, RatioP3, RatioP97; }')
    L.append('        public static readonly Dictionary<string, Group> Groups = new()')
    L.append('        {')
    for key, g in A['groups'].items():
        m, r = g['measures'], g['ratios']
        cov = [x for row in m['cov'] for x in row]
        L.append(f'            ["{key}"] = new Group')
        L.append('            {')
        L.append(f'                Mean = {arr(m["mean"])},')
        L.append(f'                Cov = {arr(cov)},')
        L.append(f'                P3 = {arr(m["p3"])}, P97 = {arr(m["p97"])},')
        L.append(f'                RatioP3 = {arr(r["p3"], 4)}, RatioP97 = {arr(r["p97"], 4)},')
        L.append('            },')
    L.append('        };')
    L.append('    }')
    L.append('}')
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
