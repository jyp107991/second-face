import json, os, re

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')


def ts(obj):
    s = json.dumps(obj, indent=2)
    s = re.sub(r'"([A-Za-z_][A-Za-z0-9_]*)":', r'\1:', s)
    s = re.sub(r'"hex:(0x[0-9a-fA-F]+)"', r'\1', s)
    return s


def grid(W, H, ch):
    return [[ch] * W for _ in range(H)]


def fill(g, x0, y0, x1, y1, ch):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = ch


def building(g, x0, y0, x1, y1, wall, floor, doors):
    fill(g, x0, y0, x1, y1, wall)
    fill(g, x0 + 1, y0 + 1, x1 - 1, y1 - 1, floor)
    for (x, y) in doors:
        g[y][x] = floor


def write(name, obj):
    header = f"import type {{ MapDef }} from '../../engine/data/types';\n\n// Generated by tools/maps/gen_md_stacks.py — edit the generator, then re-run it.\n"
    with open(os.path.join(ROOT, 'src', 'content', 'maps', f'{name}.ts'), 'w') as f:
        f.write(f"{header}export const {name}: MapDef = {ts(obj)};\n")
    print(name, len(obj['layout'][0]), 'x', len(obj['layout']))


