"""Generates the roadside maps road encounters play on: src/content/maps/wild_track.ts (a dirt track across sand)
and src/content/maps/wild_rough.ts (broken ground, a gully, salt crust). Both have the same named spots so any
encounter can use either: 'here' (where you stand), 'ahead', 'ahead2', 'side', 'side2', 'fire', 'far'.
    python3 tools/maps/gen_wilds.py
"""
import json, os, re

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')


def ts(obj):
    s = json.dumps(obj, indent=2)
    s = re.sub(r'"([A-Za-z_][A-Za-z0-9_]*)":', r'\1:', s)
    s = re.sub(r'"hex:(0x[0-9a-fA-F]+)"', r'\1', s)
    return s


def grid(w, h, ch):
    return [[ch] * w for _ in range(h)]


def fill(g, x0, y0, x1, y1, ch):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = ch


def write(m):
    with open(os.path.join(ROOT, 'src', 'content', 'maps', f"{m['id']}.ts"), 'w') as f:
        f.write(f"import type {{ MapDef }} from '../../engine/data/types';\n\n// Generated by tools/maps/gen_wilds.py — edit the generator, then re-run it.\nexport const {m['id']}: MapDef = {ts(m)};\n")
    print(m['id'], len(m['layout'][0]), 'x', len(m['layout']))


