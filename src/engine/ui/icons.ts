const WEAR_RECIPE: Record<string, string> = { coat: 'coat', plates: 'plates', hardhat: 'hardhat', headwrap: 'hood' };

/** Which sketch an item uses. */
export function iconRecipe(d: ItemDef): string {
  if (d.icon && R[d.icon]) return d.icon;
  if (d.held && R[d.held]) return d.held;
  if (d.wear) {
    if (d.wear.mask) return 'mask';
    for (const g of d.wear.gear ?? []) if (WEAR_RECIPE[g.kind]) return WEAR_RECIPE[g.kind];
    if (d.wear.garments) return d.wear.garments.some((g) => /coat|cardigan|duster/.test(typeof g.name === 'string' ? g.name : g.name.m)) ? 'coat' : 'coverall';
    if (d.wear.garment) return d.armor?.slot === 'head' ? 'hood' : typeof d.wear.garment === 'object' ? 'vest' : 'coverall';
  }
  if (d.ammo) return d.ammo.type.includes('ga') ? 'shell' : d.ammo.type === 'cell' ? 'cell' : 'cartridge';
  return R[d.category] ? d.category : 'misc';
}

export const ICON_RECIPES = Object.keys(R);

const cache = new Map<string, string>();

/** A data URL for the item's sketch at `size` px (cached). */
export function itemIcon(d: ItemDef, size = 28, ink = '#3b2a1c'): string {
  const recipe = iconRecipe(d);
  const key = `${recipe}/${size}/${ink}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const url = drawIcon(recipe, size, ink);
  cache.set(key, url);
  return url;
}

function drawIcon(recipe: string, size: number, ink: string): string {
  const c = document.createElement('canvas');
  const dpr = Math.min(2, window.devicePixelRatio || 1);
  c.width = c.height = Math.round(size * dpr);
  const ctx = c.getContext('2d');
  if (!ctx) return '';
  ctx.scale((size * dpr) / 100, (size * dpr) / 100);
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  // A seeded wobble per recipe so the same sketch always comes out the same.
  let seed = 0;
  for (const ch of recipe) seed = (seed * 31 + ch.charCodeAt(0)) >>> 0;
  const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296 - 0.5; };
  for (const s of R[recipe] ?? R.misc) {
    if (s[0] === 'f') {
      ctx.fillStyle = ink;
      ctx.globalAlpha = 0.12;
      ctx.beginPath();
      const pts = s.slice(1) as number[];
      ctx.moveTo(pts[0], pts[1]);
      for (let i = 2; i < pts.length; i += 2) ctx.lineTo(pts[i], pts[i + 1]);
      ctx.closePath();
      ctx.fill();
      ctx.globalAlpha = 1;
      continue;
    }
    // Two passes, slightly offset: a pencil line rather than a vector one.
    for (let pass = 0; pass < 2; pass++) {
      ctx.strokeStyle = ink;
      ctx.globalAlpha = pass ? 0.45 : 0.85;
      ctx.lineWidth = pass ? 3.2 : 4;
      ctx.beginPath();
      if (s[0] === 'c') {
        const [, cx, cy, r] = s as ['c', number, number, number];
        ctx.arc(cx + rnd() * 1.5, cy + rnd() * 1.5, r, 0, Math.PI * 2);
      } else {
        const pts = s as number[];
        ctx.moveTo(pts[0] + rnd() * 2, pts[1] + rnd() * 2);
        for (let i = 2; i < pts.length; i += 2) ctx.lineTo(pts[i] + rnd() * 2, pts[i + 1] + rnd() * 2);
      }
      ctx.stroke();
    }
  }
  ctx.globalAlpha = 1;
  return c.toDataURL('image/png');
}
